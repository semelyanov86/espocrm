#!/usr/bin/env bash
# Isolated test telephony of the local stand (stage 07.1, D-172): the test PBX (deploy/telephony, Docker, internal
# network) and the AMI listener of EspoCRM (systemd unit $TELEPHONY_UNIT as $ESPO_USER).
#
#   scripts/stand/telephony.sh up        # build/start the containers, configure EspoCRM, start the listener
#   scripts/stand/telephony.sh down      # switch the integration off, stop the listener and the containers
#   scripts/stand/telephony.sh status    # listener, PBX, registrations, AMI rights (no numbers, no secrets)
#   scripts/stand/telephony.sh reload    # restart the listener if it runs (after task model:apply)
#
# Secrets: $TELEPHONY_PRIVATE_DIR/secrets.env (600, generated once), handed to the containers by Docker and to EspoCRM
# through stdin (itvolga-setup-telephony), never through argv. Recordings of the test PBX (synthetic audio) are kept
# in $TELEPHONY_MONITOR_DIR, readable by $ESPO_USER through an ACL — the way proposed for production.
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

COMPOSE_FILE="$REPO_ROOT/deploy/telephony/compose.yaml"
SECRETS="$TELEPHONY_PRIVATE_DIR/secrets.env"
UNIT_FILE="/etc/systemd/system/$TELEPHONY_UNIT.service"
STATUS_FILE="$ESPO_ROOT/data/itvolga-telephony-status.json"
EXTENSIONS=(111 112 113 116 117 118 216 218)

compose() {
    ESPO_GID="$(getent group "$ESPO_USER" | cut -d: -f3)" \
    TELEPHONY_NET_PREFIX="$TELEPHONY_NET_PREFIX" TELEPHONY_PRIVATE_DIR="$TELEPHONY_PRIVATE_DIR" \
    TELEPHONY_MONITOR_DIR="$TELEPHONY_MONITOR_DIR" TELEPHONY_RUN_DIR="$TELEPHONY_RUN_DIR" \
        docker compose -p "$TELEPHONY_PROJECT" -f "$COMPOSE_FILE" "$@"
}

pbx() { docker exec "$TELEPHONY_PROJECT-pbx-1" asterisk -rx "$1"; }

listener_state() { # state field of the status file, or "none"
    as_root python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("state", "?"))' "$STATUS_FILE" \
        2>/dev/null || echo none
}

# EspoCRM settings of the integration as JSON on stdin; the secrets reach only this python process and PHP's stdin.
# The stand's fallback extension is set only when EspoCRM has none (an administrator's or a restored value stays).
setup_espo() { # enabled(true|false)
    local enabled="$1"
    if [[ "$enabled" == false ]]; then
        printf '{"enabled": false}' | espo_cmd itvolga-setup-telephony
        return
    fi
    (
        set -a; source "$SECRETS"; set +a
        TEL_SOCKET="unix://$TELEPHONY_RUN_DIR/ami.sock" TEL_ROOT="$TELEPHONY_MONITOR_DIR" \
        TEL_FALLBACK="$TELEPHONY_FALLBACK_EXTENSION" \
        python3 -c '
import json, os
data = {
    "enabled": True,
    "ami": {
        "address": os.environ["TEL_SOCKET"],
        "listener": {"username": "itvolga-espo-listener", "secret": os.environ["AMI_LISTENER_SECRET"]},
        "dialer": {"username": "itvolga-espo-dialer", "secret": os.environ["AMI_DIALER_SECRET"]},
    },
    # The production rules plus the second outbound route of the test PBX (production: another trunk variable
    # of sub-ifrussia pointing to trunk-russia; deploy/telephony/pbx/extensions.conf).
    "rules": {"trunks": {"trunk-russia": "inbound", "trunk-megafon": "inbound", "trunk-nedost": "inbound",
                         "trunk-easybell": "ignored"},
              "originateTimeout": 20000},
    "recordings": {"root": os.environ["TEL_ROOT"], "asteriskDir": "/var/spool/asterisk/monitor"},
}
data["fallbackExtensionIfMissing"] = os.environ["TEL_FALLBACK"]
print(json.dumps(data))'
    ) | espo_cmd itvolga-setup-telephony
}

wait_for() { # seconds description command...
    local seconds="$1" what="$2"; shift 2
    for _ in $(seq "$seconds"); do
        if "$@" >/dev/null 2>&1; then return 0; fi
        sleep 1
    done
    die "timeout: $what"
}

registered() { [[ "$(pbx 'pjsip show contacts' 2>/dev/null | grep -c '^  Contact:  [12][0-9][0-9]/')" -ge ${#EXTENSIONS[@]} ]]; }
pbx_ready() { pbx 'core show version' 2>/dev/null | grep -q '^Asterisk 22\.5\.2'; }
socket_ready() { as_root test -S "$TELEPHONY_RUN_DIR/ami.sock"; }
listener_connected() { [[ "$(listener_state)" == connected ]]; }

cmd_up() {
    [[ $EUID -ne 0 ]] || die "run as the developer user, not root"
    docker info >/dev/null 2>&1 || die "Docker is not available to $(id -un)"
    docker compose version >/dev/null 2>&1 || die "docker compose plugin is missing"

    install -d -m 0700 "$TELEPHONY_PRIVATE_DIR"
    if [[ ! -f "$SECRETS" ]]; then
        (umask 077; {
            echo "# AMI secrets of the stand test PBX (generated by scripts/stand/telephony.sh); not used anywhere else."
            echo "AMI_LISTENER_SECRET=$(random_secret 32)"
            echo "AMI_DIALER_SECRET=$(random_secret 32)"
        } >"$SECRETS")
        log "generated $SECRETS"
    fi
    [[ "$(stat -c %a "$SECRETS")" == 600 ]] || die "$SECRETS must have mode 600"

    # Recordings: written by asterisk inside the container (uid $TELEPHONY_ASTERISK_UID), read by $ESPO_USER via ACL.
    # uninstall --purge removes only a directory with the marker: never mark a directory the stand did not create.
    if as_root test -e "$TELEPHONY_STATE_DIR" && ! as_root test -f "$TELEPHONY_STATE_DIR/$TELEPHONY_MARKER"; then
        die "$TELEPHONY_STATE_DIR exists without $TELEPHONY_MARKER: not created by the stand telephony"
    fi
    if ! as_root test -e "$TELEPHONY_STATE_DIR"; then
        as_root install -d -m 0755 "$TELEPHONY_STATE_DIR"
        as_root touch "$TELEPHONY_STATE_DIR/$TELEPHONY_MARKER"
    fi
    as_root install -d -m 0750 -o "$TELEPHONY_ASTERISK_UID" -g "$TELEPHONY_ASTERISK_GID" "$TELEPHONY_MONITOR_DIR"
    as_root setfacl -m "u:$ESPO_USER:rx" -m "d:u:$ESPO_USER:rx" "$TELEPHONY_MONITOR_DIR"
    as_root install -d -m 0750 -o root -g "$ESPO_USER" "$TELEPHONY_RUN_DIR"

    log "starting the test PBX ($TELEPHONY_PROJECT)"
    compose up -d --build --quiet-pull >/dev/null
    wait_for 60 "AMI socket of the PBX" socket_ready
    wait_for 60 "Asterisk 22.5.2 in the test PBX" pbx_ready
    wait_for 60 "registration of ${#EXTENSIONS[@]} desk phones" registered

    setup_espo true
    espo_cmd itvolga-setup-telephony --check

    render_to itvolga-espo-telephony.service.tmpl "$UNIT_FILE" 0644
    [[ $RENDER_CHANGED == 1 ]] && as_root systemctl daemon-reload
    as_root systemctl restart "$TELEPHONY_UNIT"
    wait_for 30 "listener connected to the AMI" listener_connected
    log "telephony is up: listener connected, ${#EXTENSIONS[@]} desk phones registered"
}

cmd_down() {
    if unit_active "$MYSQL_UNIT" && as_root test -f "$ESPO_ROOT/data/config.php"; then
        setup_espo false >/dev/null || warn "could not switch the integration off in EspoCRM"
    fi
    if as_root test -f "$UNIT_FILE"; then
        as_root systemctl stop "$TELEPHONY_UNIT" || true
    fi
    if docker info >/dev/null 2>&1; then
        compose down --timeout 5 >/dev/null 2>&1 || true
    fi
    log "telephony is down (recordings stay in $TELEPHONY_MONITOR_DIR)"
}

cmd_status() {
    printf '%-24s %s\n' "listener unit" "$(systemctl is-active "$TELEPHONY_UNIT" 2>/dev/null || true)"
    if as_root test -f "$STATUS_FILE"; then
        as_root python3 -c '
import json, sys, datetime
d = json.load(open(sys.argv[1]))
alive = d.get("aliveAt")
age = "?"
if alive:
    age = int((datetime.datetime.now(datetime.timezone.utc)
               - datetime.datetime.strptime(alive, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=datetime.timezone.utc)).total_seconds())
print("%-24s %s (alive %s s ago)" % ("listener state", d.get("state"), age))
for key in ("events", "writes", "calls", "liveCalls", "ambiguousExtensions"):
    print("%-24s %s" % (key, d.get(key, "-")))' "$STATUS_FILE"
    fi
    printf '%-24s %s\n' "containers" "$(docker ps --filter "label=com.docker.compose.project=$TELEPHONY_PROJECT" -q 2>/dev/null | wc -l) running"
    if docker ps -q --filter "name=$TELEPHONY_PROJECT-pbx-1" | grep -q .; then
        printf '%-24s %s\n' "registered phones" "$(pbx 'pjsip show contacts' | grep -c '^  Contact:  [12][0-9][0-9]/')"
        printf '%-24s %s\n' "active channels" "$(pbx 'core show channels count' | head -1)"
    fi
    if [[ "${1:-}" == --check ]]; then
        espo_cmd itvolga-setup-telephony --check
    fi
}

cmd_reload() {
    if unit_active "$TELEPHONY_UNIT"; then
        as_root systemctl restart "$TELEPHONY_UNIT"
        log "listener restarted"
    fi
}

case "${1:-}" in
    up) cmd_up ;;
    down) cmd_down ;;
    status) shift; cmd_status "$@" ;;
    reload) cmd_reload ;;
    *) die "usage: telephony.sh up|down|status [--check]|reload" ;;
esac
